#!/bin/zsh
# Lift the SPURS job binaries Asuras Wrath dispatches from its job chain.
#
#   tools/lift_jobs.sh
#
# A job binary is a raw code+data blob, not an SPU ELF, so lift_spu.sh does
# not find it. With no lift the chain walker reports "dispatch MISS" and skips
# it: the skinning chain then never completes a job, and a game started from
# the menu sits on a black screen.
#
# Input: known jobs extracted from ASURA_EBOOT by extract_jobs.py, plus
# cache/jobs/spujob_<fingerprint>_<size>.bin written by a run with
# SPU_DUMP_MISS=$ASURA_ROOT/cache/jobs (enter New Game from the menu so the
# skinning chain dispatches them). Seen so far:
#   8B2B4776E3A079D8  17552 bytes  NTG SPU skinning job
#   37DA975A7C220171    112 bytes  small chain job dispatched beside it
#
# Output: port/spu/job_<fp>/spu_recomp.{c,h} (never commit: derived from game
# code) and port/spu/jobmods_register.c (fingerprints and names only).
set -e
here=${0:A:h}; source "$here/env.sh"
# Bootstrap the known jobs directly from the disc executable.
"$PY" "$here/extract_jobs.py" "$ASURA_EBOOT" -o "$ASURA_ROOT/cache/jobs"
"$PY" - "$ASURA_ROOT" "$PS3RECOMP_DIR" <<'PYEOF'
import glob, os, re, subprocess, sys
root, kit = sys.argv[1], sys.argv[2]
sys.path.insert(0, f"{kit}/tools")
from wrap_spu_elf import wrap
FIRST_IMAGE_ID = 21   # the EBOOT's embedded SPU images are 1-20
spu = f"{root}/port/spu"
jobs = []
for path in sorted(glob.glob(f"{root}/cache/jobs/spujob_*.bin")):
    fp = re.match(r"spujob_([0-9A-F]{16})_", os.path.basename(path)).group(1)
    prefix, out = f"job_{fp}_", f"{spu}/job_{fp}"
    elf = f"{root}/cache/jobs/{fp}.elf"
    # jm2 loads a job at LS 0 and enters it there (runtime/spu/spurs_job.c).
    open(elf, "wb").write(wrap(open(path, "rb").read(), base=0, entry=0))
    subprocess.check_call([sys.executable, f"{kit}/tools/spu_lifter.py", "--auto-functions", elf,
        "--base", "0x0", "--symbol-prefix", prefix, "-o", out, "--merge-chunks",
        "--source-name", "spu_recomp.c", "--header-name", "spu_recomp.h"],
        stdout=subprocess.DEVNULL)
    os.remove(elf)
    jobs.append((fp, prefix))
    print(f"[lift_jobs] {os.path.basename(path)} -> job_{fp}")

with open(f"{spu}/jobmods_register.c", "w") as f:
    f.write("/* GENERATED by tools/lift_jobs.sh: the job binaries the chain dispatches. */\n")
    f.write('#include "spu_workload.h"\n')
    f.write("extern void spu_begin_image(int image_id);\n")
    for fp, prefix in jobs:
        f.write(f"extern void {prefix}spu_func_00000000(spu_context*);\n")
        f.write(f"extern void {prefix}spu_recomp_register(void);\n")
    f.write("__attribute__((constructor)) static void jobmods_register(void)\n{\n")
    for i, (fp, prefix) in enumerate(jobs):
        image = FIRST_IMAGE_ID + i
        f.write(f"    spu_begin_image({image}); {prefix}spu_recomp_register();\n")
        f.write(f"    spu_workload_register_img(0x{fp}ULL, {prefix}spu_func_00000000, {image}, "
                f'"job_{fp}");\n')
    f.write("    spu_begin_image(0);\n}\n")
print(f"{len(jobs)} job(s) lifted")
PYEOF
